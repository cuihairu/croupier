#!/usr/bin/env bash
#
# 将 goctl 生成的 types.go 按模块拆分成多个文件
# 用法: ./scripts/split-types.sh
#

# 清理临时文件
TEMP_DIR=$(mktemp -d)
trap "rm -rf $TEMP_DIR" EXIT

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
TYPES_DIR="${SCRIPT_DIR}/../internal/types"
TYPES_FILE="${TYPES_DIR}/types.go"
BACKUP_DIR="${TYPES_DIR}/.backup"

# 颜色输出
GREEN='\033[0;32m'
YELLOW='\033[0;33m'
RED='\033[0;31m'
NC='\033[0m'

log_info() { echo -e "${GREEN}[INFO]${NC} $1"; }
log_error() { echo -e "${RED}[ERROR]${NC} $1"; }

if [[ ! -f "$TYPES_FILE" ]]; then
    log_error "找不到 $TYPES_FILE"
    exit 1
fi

# 备份
log_info "备份原始文件..."
mkdir -p "$BACKUP_DIR"
cp "$TYPES_FILE" "$BACKUP_DIR/types.go.bak"

# 清理旧的拆分文件
log_info "清理旧的拆分文件..."
find "$TYPES_DIR" -maxdepth 1 -name "*.go" ! -name "types.go" ! -name "admin_games.go" -delete 2>/dev/null || true

# 根据类型名确定输出文件
get_file_for_type() {
    type_name="$1"

    case "$type_name" in
        Admin*|Role*|Permission*)    echo "admin.go";;
        Login*|Logout*|UserInfo*)     echo "auth.go";;
        Profile*)                    echo "profile.go";;
        Game*)                       echo "game.go";;
        Function*)                   echo "function.go";;
        Descriptor*)                 echo "descriptor.go";;
        Player*)                     echo "player.go";;
        Job*)                        echo "job.go";;
        Agent*)                      echo "agent.go";;
        Ops*)                        echo "ops.go";;
        Behavior*|Payments*|Retention*|Overview*|Episode*|Level*|Map*|Funnel*|Path*|Realtime*)  echo "analytics.go";;
        Node*)                       echo "node.go";;
        Backup*)                     echo "backup.go";;
        Config*)                     echo "config.go";;
        Schema*)                     echo "schema.go";;
        Pack*)                       echo "pack.go";;
        RateLimit*)                  echo "rate_limit.go";;
        Registry*)                   echo "registry.go";;
        Alert*|Silence*)             echo "alert.go";;
        Message*)                    echo "message.go";;
        Ticket*|Comment*)            echo "ticket.go";;
        Feedback*)                   echo "feedback.go";;
        FAQ*)                        echo "faq.go";;
        Certificate*)                echo "certificate.go";;
        Entity*)                     echo "entity.go";;
        Provider*)                   echo "provider.go";;
        Component*)                  echo "component.go";;
        XRender*)                    echo "xrender.go";;
        Platform*|ListPlatform*)     echo "platform.go";;
        Assignment*)                 echo "assignment.go";;
        Approval*)                   echo "approval.go";;
        Audit*)                      echo "audit.go";;
        Metrics*|Healthz*)           echo "metrics.go";;
        Ingest*|Provider*|Reload*|List*|Call*|SignedUrl*|Stream*|Root*|Status*)  echo "provider.go";;
        *)                           echo "common.go";;
    esac
}

# 解析 types.go
log_info "解析并拆分 types.go..."

current_type=""
current_file=""

while IFS= read -r line || [[ -n "$line" ]]; do
    # 跳过文件头、package、import
    if [[ "$line" =~ ^//(Code\ generated|goctl) ]] || \
       [[ "$line" =~ ^package ]] || \
       [[ "$line" =~ ^import ]] || \
       [[ "$line" =~ ^\(|^\)$ ]]; then
        continue
    fi

    # 检测类型定义开始
    if [[ "$line" =~ ^type[[:space:]]+([A-Za-z][A-Za-z0-9_]*)[[:space:]]+(struct|interface) ]]; then
        type_name="${BASH_REMATCH[1]}"
        output_file=$(get_file_for_type "$type_name")
        current_file="$output_file"
        current_type="$type_name"
        echo "$line" >> "$TEMP_DIR/$output_file"
    elif [[ -n "$current_type" ]]; then
        echo "$line" >> "$TEMP_DIR/$current_file"
        # 检测类型定义结束
        if [[ "$line" =~ ^\} ]]; then
            current_type=""
        fi
    fi
done < "$TYPES_FILE"

# 生成最终文件
log_info "生成拆分文件..."

for temp_file in "$TEMP_DIR"/*; do
    [[ -f "$temp_file" ]] || continue
    filename=$(basename "$temp_file")
    output_path="${TYPES_DIR}/${filename}"

    # 检查是否需要 time import
    need_time=""
    if grep -q "time.Time" "$temp_file"; then
        need_time=$'\n''import ('$'\n''	"time"'$'\n'')'$'\n'
    fi

    # 写入文件
    cat > "$output_path" << EOF
// Code generated by goctl. DO NOT EDIT.
// This file is automatically split from types.go by scripts/split-types.sh

package types
$need_time
EOF

    cat "$temp_file" >> "$output_path"

    count=$(grep -c "^type " "$output_path" 2>/dev/null || echo "0")
    log_info "  ✓ $filename ($count types)"
done

# 重写 types.go 作为索引
log_info "重写 types.go 索引..."
cat > "$TYPES_FILE" << 'EOF'
// Code generated by goctl. DO NOT EDIT.
//
// 此文件由 scripts/split-types.sh 自动生成
// 所有类型定义已拆分到以下模块文件中

package types

// 本文件保留作为兼容性入口，实际类型定义在:
EOF

for f in "$TEMP_DIR"/*; do
    [[ -f "$f" ]] || continue
    echo "//   - $(basename "$f")" >> "$TYPES_FILE"
done

file_count=$(ls -1 "$TEMP_DIR" 2>/dev/null | wc -l)
log_info ""
log_info "完成！共拆分到 $file_count 个文件"
