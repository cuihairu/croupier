// The devops session relay panel surface (AGENT-002): the panel opens / feeds /
// resizes / closes SSH sessions to the devops agent through the server proxy, and
// output streams back to the panel via SSE. Authorization and scoping happen at
// this layer (the operator comes from the server's authenticated identity and is
// sent down with open for the agent's audit chain); the allowlist / data-plane
// audit / backpressure truth lives on the agent side (Broker/Hub) — this layer only
// routes and leaves a trail: open/close land in the server audit
// (devops.session_open/close); keyboard input and output do not land in the server
// audit (the agent execlog is the complete truth; double-writing would only create
// two drifting ledgers).
