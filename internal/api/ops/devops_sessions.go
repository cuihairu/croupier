// errDevopsRelayNotConfigured is the 503 returned when the hub is not wired (the
// devops relay is not connected).
var errDevopsRelayNotConfigured = &errorx.CodeError{
	Code:       http.StatusServiceUnavailable,
	Message:    "devops session relay not configured",
	StableCode: "devops_relay_not_configured",
}

// ---- DTO (contract keys are lowerCamelCase) ----

// DevopsSessionOpenRequest opens a session to host:port via the specified devops agent.
type DevopsSessionOpenRequest struct {
	AgentID  string `json:"agentId"`
	Protocol string `json:"protocol"`
	Host     string `json:"host"`
	Port     int32  `json:"port"`
	Cols     int32  `json:"cols,omitempty"`
	Rows     int32  `json:"rows,omitempty"`
}

// DevopsSessionOpenResponse is the session-open result (the session ID is generated by the server).
type DevopsSessionOpenResponse struct {
	SessionID string `json:"sessionId"`
	AgentID   string `json:"agentId"`
	Protocol  string `json:"protocol"`
	Host      string `json:"host"`
	Port      int32  `json:"port"`
	Channel   string `json:"channel,omitempty"`
}

// DevopsSessionItem is a proxied-session list entry.
type DevopsSessionItem struct {
	SessionID string `json:"sessionId"`
	AgentID   string `json:"agentId"`
	Operator  string `json:"operator"`
	Protocol  string `json:"protocol"`
	Host      string `json:"host"`
	Port      int32  `json:"port"`
	Channel   string `json:"channel,omitempty"`
	CreatedAt string `json:"createdAt"`
}

// DevopsSessionListResponse is the proxied-session list.
type DevopsSessionListResponse struct {
	Sessions []DevopsSessionItem `json:"sessions"`
}

// DevopsSessionInputRequest is keyboard data (text; Enter includes \n).
type DevopsSessionInputRequest struct {
	Data string `json:"data"`
}

// DevopsSessionResizeRequest is the terminal window (cols x rows).
type DevopsSessionResizeRequest struct {
	Cols int32 `json:"cols"`
	Rows int32 `json:"rows"`
}

// DevopsSessionCloseRequest is the reason for an active close (audited; a bodyless DELETE is also valid).
type DevopsSessionCloseRequest struct {
	Reason string `json:"reason,omitempty"`
}

